function normalizeLanguage(value: string | null | undefined): AppLanguage {
  return value === "fr" || value === "ar" || value === "en" ? value : "en"
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("en")

  useEffect(() => {
    const saved = normalizeLanguage(window.localStorage.getItem(STORAGE_KEY))
    setLanguageState(saved)
  }, [])

  const setLanguage = (nextLanguage: AppLanguage) => {
    setLanguageState(nextLanguage)
    window.localStorage.setItem(STORAGE_KEY, nextLanguage)
  }

  const languageMeta = languages.find((item) => item.code === language) || languages[0]

  useEffect(() => {
    document.documentElement.lang = language
    document.documentElement.dir = languageMeta.dir
  }, [language, languageMeta.dir])

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage,
      dir: languageMeta.dir,
      t: (key: string) => dictionaries[language][key] || dictionaries.en[key] || key,
      tr: (text: string) => language === "en" ? text : phraseTranslations[language][text] || text,
    }),
    [language, languageMeta.dir]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider")
  }
  return context
}
